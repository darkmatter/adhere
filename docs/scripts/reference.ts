// Generates the Reference pages from the source, so they can't drift from it:
// the commands page from the CLI's help data, and the config page from the
// config schema's description annotations. Run before `astro dev` and `astro build`.
import { mkdirSync, writeFileSync } from "node:fs";
import { Option, Schema, SchemaAST, SchemaRepresentation } from "effect";
import { cli } from "../../src/cli.ts";
import { AdhereConfig, Rule } from "../../src/config.ts";

const out = new URL("../src/content/docs/reference/", import.meta.url);
const note = (from: string) =>
  `<!-- Generated by docs/scripts/reference.ts from ${from}. Do not edit. -->`;

// `buildHelpDoc` is what `--help` renders from. It is internal to Effect's
// CLI, so an Effect upgrade that changes it fails this script, and the build.
interface FlagDoc {
  name: string;
  aliases: ReadonlyArray<string>;
  type: string;
  description: Option.Option<string>;
}
interface ArgDoc {
  name: string;
  type: string;
  description: Option.Option<string>;
  required: boolean;
  variadic: boolean;
}
interface HelpDoc {
  description: string;
  usage: string;
  flags: ReadonlyArray<FlagDoc>;
  args?: ReadonlyArray<ArgDoc>;
  examples?: ReadonlyArray<{ command: string; description?: string }>;
}
interface Documented {
  name: string;
  subcommands: ReadonlyArray<{ commands: ReadonlyArray<Documented> }>;
  buildHelpDoc: (path: ReadonlyArray<string>) => HelpDoc;
}

const flagName = (flag: FlagDoc) =>
  [...flag.aliases, `--${flag.name}`].map((name) => `\`${name}\``).join(", ") +
  (flag.type === "boolean" ? "" : ` \`<${flag.type}>\``);

const describe = (description: Option.Option<string>) =>
  Option.match(description, { onNone: () => "", onSome: (text) => ` ${text}` });

const commandSection = (command: Documented, trail: ReadonlyArray<string>): string => {
  const path = [...trail, command.name];
  const doc = command.buildHelpDoc(["adhere", ...path]);
  const lines = [`## ${path.join(" ")}`, "", doc.description, "", "```sh", doc.usage, "```"];
  if (doc.args?.length) {
    lines.push("", "### Arguments", "");
    for (const arg of doc.args)
      lines.push(
        `- **\`<${arg.name}>\`${arg.required ? "" : " (optional)"}.**${describe(arg.description)}`,
      );
  }
  if (doc.flags.length) {
    lines.push("", "### Flags", "");
    for (const flag of doc.flags)
      lines.push(`- **${flagName(flag)}.**${describe(flag.description)}`);
  }
  const children = command.subcommands.flatMap((group) =>
    group.commands.map((child) => commandSection(child, [...trail, command.name])),
  );
  return [lines.join("\n"), ...children].join("\n\n");
};

const root = cli as unknown as Documented;
const rootDoc = root.buildHelpDoc(["adhere"]);
const commands = [
  "---",
  "title: Commands",
  "description: Every adhere command and flag.",
  "---",
  "",
  note("src/cli.ts"),
  "",
  rootDoc.description,
  "",
  "Bare `adhere` prints the help. `adhere <command> --help` lists a command's flags, and `adhere --completions <shell>` prints a completion script.",
  "",
  ...(rootDoc.examples?.length
    ? [
        "```sh",
        ...rootDoc.examples.flatMap((example) => [
          ...(example.description ? [`# ${example.description}`] : []),
          example.command,
        ]),
        "```",
        "",
      ]
    : []),
  root.subcommands
    .flatMap((group) => group.commands.map((command) => commandSection(command, [])))
    .join("\n\n"),
  "",
].join("\n");

// The config page reads each key's description and type off the schema, as
// a config file writes it: `Schema.toEncoded` makes defaulted keys optional.
const keyList = (fields: Readonly<Record<string, Schema.Top>>) =>
  Object.entries(fields)
    .map(([key, field]) => {
      const encoded = Schema.toEncoded(field);
      const optional = encoded.ast.context?.isOptional === true;
      const typeText = SchemaRepresentation.toCodeDocument(
        SchemaRepresentation.toMultiDocument(Schema.toRepresentation(encoded)),
      ).codes[0]!.Type.replaceAll("readonly ", "");
      const description = SchemaAST.resolveDescription(field.ast);
      if (!description) throw new Error(`${key} in src/config.ts has no description annotation`);
      return `### \`${key}\`${optional ? "" : " (required)"}\n\n\`\`\`ts\n${typeText}\n\`\`\`\n\n${description}`;
    })
    .join("\n\n");

const config = [
  "---",
  "title: Config file",
  "description: Every key a config file takes.",
  "---",
  "",
  note("src/config.ts"),
  "",
  "Every key a config file's `defineConfig({...})` takes. See [Config](/adhere/config/) for where the file goes and how its settings combine.",
  "",
  "## Config keys",
  "",
  keyList(AdhereConfig.fields),
  "",
  "## Rule keys",
  "",
  "The keys of an inline rule in `rules`, or of a rule written in TypeScript with `defineRule`.",
  "",
  keyList(Rule.fields),
  "",
].join("\n");

mkdirSync(out, { recursive: true });
writeFileSync(new URL("commands.md", out), commands);
writeFileSync(new URL("config-file.md", out), config);
